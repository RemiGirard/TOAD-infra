function generateSimpleInventory(stackName: string, outputs: Record<string, string>): string {
  return `# Ansible inventory for ${stackName}
# Generated by: pnpm run inventory ${stackName}

all:
  vars:
    ansible_user: ubuntu
    ansible_ssh_private_key_file: ${SSH_KEY_PATH}
    ansible_ssh_common_args: '-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null'

  hosts:
    toad-node:
      ansible_host: ${outputs.floating_ip}
`;
}

export async function run(args: string[]): Promise<void> {
  banner('TOAD Ansible Inventory Generator');

  const stackName = args[0];

  if (!stackName) {
    console.log('Usage: pnpm run inventory <stack-name>\n');
    console.log('Available stacks:');

    try {
      const stacks = listStacks(openstackStackRepository);
      if (stacks.length > 0) {
        stacks.forEach(s => console.log(`  ${s.name}`));
      } else {
        console.log('(no stacks found)');
      }
    } catch {
      console.log('(failed to list stacks)');
    }
    process.exit(1);
  }

  console.log(`Generating inventory for stack: ${stackName}\n`);

  // Get stack outputs
  let outputs: Record<string, string>;
  try {
    outputs = getStackOutputs(openstackStackRepository, stackName);
  } catch {
    error('Failed to get stack outputs. Is the stack deployed?');
    process.exit(1);
  }

  // Generate inventory based on stack type
  let inventory: string;

  if (outputs.bastion_floating_ip) {
    inventory = generateLevel5Inventory(stackName, outputs);
  } else if (outputs.gateway_floating_ip) {
    inventory = generateLevel4Inventory(stackName, outputs);
  } else if (outputs.floating_ip) {
    inventory = generateSimpleInventory(stackName, outputs);
  } else {
    error('Could not determine stack type from outputs');
    process.exit(1);
  }

  // Write inventory file
  const inventoryPath = join(ROOT_DIR, 'inventory.yaml');
  writeFileSync(inventoryPath, inventory);

  success('Inventory written to: inventory.yaml\n');
  console.log('Preview:');
  section('', 50);
  console.log(inventory);
  section('', 50);
  console.log('\nUsage:');
  console.log('  ansible-playbook -i inventory.yaml your-playbook.yaml');
  console.log('  ansible all -i inventory.yaml -m ping\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  run(process.argv.slice(2));
}
